    """
    FinancialExpert
    ===============

    Business Expert responsible for representing the financial
    situation of one player.

    Architectural principle
    ------------------------
    FinancialExpert is completely autonomous.

    It reads financial information directly from the game
    observation (obs) and does NOT depend on any other Business
    Expert.

    Its purpose is to transform raw game-state information into
    financial and economic features that can later be used by
    decision-making and AI/ML models.

    Main responsibilities
    ----------------------
    - cash
    - income
    - expenses
    - cash flow
    - inventory valuation
    - seed valuation
    - observable animal asset valuation
    - land value
    - total assets
    - net worth
    - liquidity
    - balance
    - investments
    - acquisition cost
    - aggregate transaction return
    - payback

    Important accounting distinction
    ---------------------------------
    A change in cash is NOT necessarily an income or an expense.

    Example:

        BUY_ANIMAL COW

    causes:

        cash              ↓
        animal asset      ↑

    Therefore, the cash movement alone cannot be interpreted as
    an economic loss.

    For this reason, income and expenses are classified from the
    explicit action whenever the action is available.

    If process_observation() is called without an action, the
    current financial state can still be calculated correctly,
    but the individual income/expense transaction cannot always
    be reconstructed reliably from obs alone.

    Important limitation about placed animals
    ------------------------------------------
    The public farm tile representation observed in Kaggriculture
    shows structures such as:

        {"kind": "PASTURE"}
        {"kind": "COOP"}

    but does not expose an "animal" field in the observations
    currently verified.

    Therefore FinancialExpert does NOT invent animal occupancy
    from the presence of a pasture or coop.

    Animals explicitly visible in the shed can be valued.
    The complete population of animals placed on the farm requires
    additional state information or action/history attribution.
    """

    # =========================================================
    # GAME FINANCIAL CONSTANTS
    # =========================================================

    ANIMAL_COSTS = {
        'GOOSE': 300,
        'COW': 400,
        'SHEEP': 500,
    }

    LAND_PRICES = [
        1000,
        2000,
        4000,
    ]

    ANIMAL_TYPES = (
        'GOOSE',
        'COW',
        'SHEEP',
    )

    # =========================================================
    # INITIALIZATION
    # =========================================================

    def __init__(self, player=0):

        self.player = player

        # -----------------------------------------------------
        # Temporal state
        # -----------------------------------------------------

        self.step = None
        self.day = None
        self.hour = None

        self.days_remaining = None
        self.steps_remaining = None
        self.season_progress = None

        self.is_last_day = False
        self.is_last_week = False
        self.is_day_start = False
        self.is_day_end = False

        # -----------------------------------------------------
        # Financial state
        # -----------------------------------------------------

        self.cash = 0
        self.income = 0
        self.expenses = 0
        self.cash_flow = 0

        # -----------------------------------------------------
        # Assets
        # -----------------------------------------------------

        self.shed = {}
        self.inventory_value = 0

        self.seeds = {}
        self.seed_value = 0

        # -----------------------------------------------------
        # Animals
        # -----------------------------------------------------

        self.animals = {}
        self.current_animals = {}

        self.animal_asset_value = 0

        # -----------------------------------------------------
        # Land
        # -----------------------------------------------------

        self.land_value = 0

        # -----------------------------------------------------
        # Net worth
        # -----------------------------------------------------

        self.net_worth = 0
        self.liquidity_ratio = 0
        self.money_per_day_remaining = 0

        # -----------------------------------------------------
        # Balance
        # -----------------------------------------------------

        self.assets = 0
        self.balance = 0

        # -----------------------------------------------------
        # Investments
        # -----------------------------------------------------

        self.investments = {}

        self.acquisition_cost = 0

        # Aggregate result of the current transaction.
        #
        # This is NOT individual ROI.
        self.investment_return = 0

        self.payback = None

        # -----------------------------------------------------
        # Market
        # -----------------------------------------------------

        self.market = {}
        self.prices = {}

        # -----------------------------------------------------
        # Historical state
        # -----------------------------------------------------

        self.previous_cash = None
        self.previous_shed = None
        self.previous_seed_value = None
        self.previous_animal_asset_value = None
        self.previous_land_value = None
        self.previous_net_worth = None

        # -----------------------------------------------------
        # Last transaction
        # -----------------------------------------------------

        self.last_transaction = None

    # =========================================================
    # PROCESS OBSERVATION
    # =========================================================

    def process_observation(self, obs, action=None):

        # -----------------------------------------------------
        # Save previous state
        # -----------------------------------------------------

        previous_cash = self.cash
        previous_shed = self.shed.copy()

        previous_seed_value = self.seed_value
        previous_animal_asset_value = self.animal_asset_value
        previous_land_value = self.land_value
        previous_net_worth = self.net_worth

        # =====================================================
        # GENERAL INFORMATION
        # =====================================================

        self.step = obs['step']
        self.day = obs['day']
        self.hour = obs['hour']

        # =====================================================
        # DERIVED TIME FEATURES
        # =====================================================

        total_steps = 720
        total_days = 30
        hours_per_day = 24

        self.days_remaining = max(
            0,
            total_days - self.day
        )

        self.steps_remaining = max(
            0,
            total_steps - self.step
        )

        self.season_progress = (
            self.step / total_steps
        )

        self.is_last_day = (
            self.day == total_days - 1
        )

        self.is_last_week = (
            self.days_remaining <= 7
        )

        self.is_day_start = (
            self.hour == 0
        )

        self.is_day_end = (
            self.hour == hours_per_day - 1
        )

        # =====================================================
        # PLAYER STATE
        # =====================================================

        self.me = obs['farms'][self.player]
        self.private = obs['private']

        self.cash = self.me['money']

        # =====================================================
        # SHED
        # =====================================================

        self.shed = dict(
            self.private.get('shed', {})
        )

        # =====================================================
        # SEEDS
        # =====================================================

        self.seeds = dict(
            self.private.get('seeds', {})
        )

        # =====================================================
        # MARKET
        # =====================================================

        self.market = obs.get('market', {})
        self.prices = self.market.get('prices', {})

        # =====================================================
        # INVENTORY VALUE
        # =====================================================

        self.inventory_value = sum(
            self.prices.get(product, 0) * quantity
            for product, quantity in self.shed.items()
            if product not in self.ANIMAL_TYPES
        )

        # =====================================================
        # SEED VALUE
        # =====================================================

        seed_prices = {
            'WHEAT': 10,
            'CARROT': 20,
            'TOMATO': 50,
            'STRAWBERRY': 100,
            'MELON': 80,
        }

        self.seed_value = sum(
            seed_prices.get(seed, 0) * quantity
            for seed, quantity in self.seeds.items()
        )

        # =====================================================
        # ANIMALS
        # =====================================================

        """
        IMPORTANT

        The currently verified public tile representation does
        not expose animal occupancy.

        Therefore we can reliably count animals stored in the shed,
        but we cannot reconstruct placed animals from:

            {"kind": "PASTURE"}

        or:

            {"kind": "COOP"}

        alone.

        We deliberately DO NOT do:

            tile.get("animal")

        and we do NOT assume:

            one pasture == one cow

        because that would create false financial data.
        """

        self.current_animals = {
            animal: 0
            for animal in self.ANIMAL_TYPES
        }

        # Observable animals currently stored in the shed.

        for animal in self.ANIMAL_TYPES:

            self.current_animals[animal] += (
                self.shed.get(animal, 0)
            )

        self.animals = self.current_animals.copy()

        # =====================================================
        # ANIMAL ASSET VALUE
        # =====================================================

        """
        Only animals explicitly observable in the current
        inventory state are valued here.

        Animals placed on the farm require additional information
        not currently exposed by the verified tile observation.
        """

        self.animal_asset_value = sum(
            self.ANIMAL_COSTS[animal] * quantity
            for animal, quantity in self.animals.items()
        )

        # =====================================================
        # LAND VALUE
        # =====================================================

        unlocked_quadrants = self.me.get(
            'unlocked_quadrants',
            ['NW']
        )

        extra_quadrants = max(
            0,
            len(unlocked_quadrants) - 1
        )

        self.land_value = sum(
            self.LAND_PRICES[:extra_quadrants]
        )

        # =====================================================
        # TOTAL ASSETS
        # =====================================================

        self.assets = (
            self.inventory_value
            + self.seed_value
            + self.animal_asset_value
            + self.land_value
        )

        # =====================================================
        # NET WORTH
        # =====================================================

        self.net_worth = (
            self.cash
            + self.assets
        )

        # =====================================================
        # LIQUIDITY
        # =====================================================

        if self.net_worth > 0:

            self.liquidity_ratio = (
                self.cash / self.net_worth
            )

        else:

            self.liquidity_ratio = 0

        # =====================================================
        # MONEY PER DAY REMAINING
        # =====================================================

        if self.days_remaining > 0:

            self.money_per_day_remaining = (
                self.cash / self.days_remaining
            )

        else:

            self.money_per_day_remaining = self.cash

        # =====================================================
        # BALANCE
        # =====================================================

        self.balance = (
            self.cash
            + self.assets
        )

        # =====================================================
        # TRANSACTION PROCESSING
        # =====================================================

        self._process_transaction(
            action=action,
            previous_cash=previous_cash,
        )

        # =====================================================
        # HISTORICAL STATE
        # =====================================================

        self.previous_cash = previous_cash
        self.previous_shed = previous_shed
        self.previous_seed_value = previous_seed_value
        self.previous_animal_asset_value = previous_animal_asset_value
        self.previous_land_value = previous_land_value
        self.previous_net_worth = previous_net_worth

    # =========================================================
    # TRANSACTION PROCESSING
    # =========================================================

    def _process_transaction(
        self,
        action,
        previous_cash,
    ):

        self.income = 0
        self.expenses = 0
        self.cash_flow = 0

        self.acquisition_cost = 0
        self.investment_return = 0
        self.payback = None

        self.last_transaction = None

        # =====================================================
        # NO ACTION
        # =====================================================

        if action is None:

            if previous_cash is not None:

                self.cash_flow = (
                    self.cash - previous_cash
                )

            return

        # =====================================================
        # NORMALIZE MARKET ACTIONS
        # =====================================================

        market_orders = []

        if isinstance(action, dict):

            market_orders = action.get(
                'market',
                []
            )

        elif isinstance(action, list):

            market_orders = action

        # =====================================================
        # MARKET ORDERS
        # =====================================================

        for order in market_orders:

            if not order:
                continue

            operation = order[0]

            # -------------------------------------------------
            # BUY_SEED
            # -------------------------------------------------

            if operation == 'BUY_SEED':

                if len(order) < 3:
                    continue

                seed = order[1]
                quantity = order[2]

                price = self._seed_price(seed)
                cost = price * quantity

                self.expenses += cost

                self.last_transaction = {
                    'type': 'expense',
                    'operation': operation,
                    'item': seed,
                    'quantity': quantity,
                    'amount': cost,
                }

            # -------------------------------------------------
            # BUY_PRODUCT
            # -------------------------------------------------

            elif operation == 'BUY_PRODUCT':

                if len(order) < 3:
                    continue

                product = order[1]
                quantity = order[2]

                price = self.prices.get(
                    product,
                    0
                )

                cost = price * quantity

                self.expenses += cost

                self.last_transaction = {
                    'type': 'expense',
                    'operation': operation,
                    'item': product,
                    'quantity': quantity,
                    'amount': cost,
                }

            # -------------------------------------------------
            # BUY_ANIMAL
            # -------------------------------------------------

            elif operation == 'BUY_ANIMAL':

                if len(order) < 3:
                    continue

                animal = order[1]
                quantity = order[2]

                unit_cost = self.ANIMAL_COSTS.get(
                    animal,
                    0
                )

                cost = unit_cost * quantity

                self.expenses += cost
                self.acquisition_cost += cost

                self.investments.setdefault(
                    'animals',
                    {
                        'type': 'productive_asset',
                        'acquisition_cost': 0,
                        'units': 0,
                        'return': 0,
                    }
                )

                self.investments[
                    'animals'
                ]['acquisition_cost'] += cost

                self.investments[
                    'animals'
                ]['units'] += quantity

                self.last_transaction = {
                    'type': 'investment',
                    'operation': operation,
                    'item': animal,
                    'quantity': quantity,
                    'amount': cost,
                }

            # -------------------------------------------------
            # SELL
            # -------------------------------------------------

            elif operation == 'SELL':

                if len(order) < 3:
                    continue

                product = order[1]
                quantity = order[2]

                price = self.prices.get(
                    product,
                    0
                )

                revenue = price * quantity

                self.income += revenue

                self.last_transaction = {
                    'type': 'income',
                    'operation': operation,
                    'item': product,
                    'quantity': quantity,
                    'amount': revenue,
                }

            # -------------------------------------------------
            # HIRE
            # -------------------------------------------------

            elif operation == 'HIRE':

                hires_today = self.me.get(
                    'hires_today',
                    0
                )

                cost = self._hire_cost(
                    hires_today
                )

                self.expenses += cost

                self.last_transaction = {
                    'type': 'expense',
                    'operation': operation,
                    'amount': cost,
                }

            # -------------------------------------------------
            # BUY_LAND
            # -------------------------------------------------

            elif operation == 'BUY_LAND':

                unlocked = self.me.get(
                    'unlocked_quadrants',
                    ['NW']
                )

                extra_quadrants = max(
                    0,
                    len(unlocked) - 1
                )

                if extra_quadrants < len(
                    self.LAND_PRICES
                ):

                    cost = self.LAND_PRICES[
                        extra_quadrants
                    ]

                    self.expenses += cost
                    self.acquisition_cost += cost

                    self.investments.setdefault(
                        'land',
                        {
                            'type': 'fixed_asset',
                            'acquisition_cost': 0,
                            'units': 0,
                            'return': 0,
                        }
                    )

                    self.investments[
                        'land'
                    ]['acquisition_cost'] += cost

                    self.investments[
                        'land'
                    ]['units'] += 1

                    self.last_transaction = {
                        'type': 'investment',
                        'operation': operation,
                        'amount': cost,
                    }

        # =====================================================
        # FARMER / HAND ACTIONS
        # =====================================================

        unit_actions = []

        if isinstance(action, dict):

            if action.get('farmer'):

                unit_actions.append(
                    action['farmer']
                )

            for hand_action in action.get(
                'hands',
                []
            ):

                unit_actions.append(
                    hand_action
                )

        # =====================================================
        # BUILDINGS
        # =====================================================

        for unit_action in unit_actions:

            if not unit_action:
                continue

            operation = unit_action[0]

            if operation in (
                'BUILD_COOP',
                'BUILD_PASTURE',
            ):

                # NOTE:
                # This remains provisional until the exact
                # construction cost is confirmed from the rules.

                cost = 1

                self.expenses += cost
                self.acquisition_cost += cost

                structure = (
                    'coop'
                    if operation == 'BUILD_COOP'
                    else 'pasture'
                )

                self.investments.setdefault(
                    structure,
                    {
                        'type': 'fixed_asset',
                        'acquisition_cost': 0,
                        'units': 0,
                        'return': 0,
                    }
                )

                self.investments[
                    structure
                ]['acquisition_cost'] += cost

                self.investments[
                    structure
                ]['units'] += 1

                self.last_transaction = {
                    'type': 'investment',
                    'operation': operation,
                    'amount': cost,
                }

        # =====================================================
        # CASH FLOW
        # =====================================================

        self.cash_flow = (
            self.income
            - self.expenses
        )

        # =====================================================
        # AGGREGATE TRANSACTION RETURN
        # =====================================================

        """
        This is deliberately NOT called ROI.

        It represents:

            income - expenses

        for the transactions currently processed.

        It does not attribute income to:

            - cows
            - sheep
            - geese
            - pasture
            - land
            - buildings

        Therefore it cannot be interpreted as the profitability
        of an individual investment.
        """

        self.investment_return = (
            self.income
            - self.expenses
        )

        # =====================================================
        # PAYBACK
        # =====================================================

        """
        Aggregate approximation only.

        Individual asset payback cannot currently be calculated
        because generated income cannot be reliably attributed
        to a specific investment.
        """

        if (
            self.acquisition_cost > 0
            and self.investment_return > 0
        ):

            self.payback = (
                self.acquisition_cost
                / self.investment_return
            )

        else:

            self.payback = None

    # =========================================================
    # SEED PRICE
    # =========================================================

    def _seed_price(self, seed):

        seed_prices = {
            'WHEAT': 10,
            'CARROT': 20,
            'TOMATO': 50,
            'STRAWBERRY': 100,
            'MELON': 80,
        }

        return seed_prices.get(
            seed,
            0
        )

    # =========================================================
    # HIRE COST
    # =========================================================

    def _hire_cost(self, hires_today):

        a = 1
        b = 1

        for _ in range(hires_today):

            a, b = b, a + b

        return a

    # =========================================================
    # FEATURES
    # =========================================================

