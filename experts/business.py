    def _process_crop(self, tile):

        crop = tile.get(
            "crop",
            "UNKNOWN"
        )

        planted_day = tile.get(
            "planted_day",
            0
        )

        yield_units = tile.get(
            "yield_units",
            0
        )

        watered_today = tile.get(
            "watered_today",
            False
        )

        consecutive_unwatered = tile.get(
            "consecutive_unwatered",
            0
        )

        fertilized_until_day = tile.get(
            "fertilized_until_day",
            -1
        )

        max_lifespan_step = tile.get(
            "max_lifespan_step",
            0
        )

        # ============================================================
        # FEATURES DERIVADAS
        # ============================================================

        crop_age = (
            self.day - planted_day
        )

        steps_remaining = (
            max_lifespan_step - self.step
        )

        # Rendimiento > 0 significa que existe producción
        # disponible según la representación actual del engine.

        is_ready = (
            yield_units > 0
        )

        # IMPORTANTE:
        #
        # "no regado hoy" y "consecutive_unwatered" son dos
        # conceptos distintos.
        #
        # watered_today responde:
        #
        #     ¿se regó hoy?
        #
        # consecutive_unwatered responde:
        #
        #     ¿cuántos períodos consecutivos lleva sin riego?

        is_unwatered = not watered_today

        is_fertilized = (
            fertilized_until_day >= self.day
        )

        # ============================================================
        # DETALLE INDIVIDUAL
        # ============================================================

        details = {
            "crop": crop,
            "planted_day": planted_day,
            "crop_age": crop_age,
            "yield_units": yield_units,

            "watered_today": watered_today,
            "is_unwatered": is_unwatered,

            "consecutive_unwatered":
                consecutive_unwatered,

            "fertilized_until_day":
                fertilized_until_day,

            "max_lifespan_step":
                max_lifespan_step,

            "steps_remaining":
                steps_remaining,

            "is_ready": is_ready,
            "is_fertilized": is_fertilized,
        }

        self.crop_details.append(details)

        # ============================================================
        # AGREGACIÓN
        # ============================================================

        if crop not in self.crops:

            self.crops[crop] = {
                "count": 0,
                "yield_units": 0,
                "ready_count": 0,
                "unwatered_count": 0,
                "fertilized_count": 0,
            }

        self.crops[crop]["count"] += 1

        self.crops[crop]["yield_units"] += (
            yield_units
        )

        if is_ready:

            self.crops[crop]["ready_count"] += 1

        if is_unwatered:

            self.crops[crop]["unwatered_count"] += 1

        if is_fertilized:

            self.crops[crop]["fertilized_count"] += 1

        # ============================================================
        # TOTALES
        # ============================================================

        self.total_plants += 1

        if is_ready:

            self.ready_plants += 1

        if is_unwatered:

            self.unwatered_plants += 1

        if is_fertilized:

            self.fertilized_plants += 1

        # ============================================================
        # PRODUCCIÓN
        # ============================================================

        self.current_yield += (
            yield_units
        )

        self.production_ready_now += (
            yield_units
        )

